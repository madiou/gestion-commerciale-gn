// Petit polyfill pour les modules qui touchent localStorage (i18n.js) : Node
// n'a pas cette API par défaut. À importer avant tout module qui en dépend.
if (typeof globalThis.localStorage === 'undefined') {
  const store = new Map();
  globalThis.localStorage = {
    getItem: (k) => (store.has(k) ? store.get(k) : null),
    setItem: (k, v) => store.set(k, String(v)),
    removeItem: (k) => store.delete(k),
    clear: () => store.clear(),
  };
}
